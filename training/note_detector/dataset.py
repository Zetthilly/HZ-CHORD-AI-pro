"""
Loads the synthetic arpeggio examples generated by
generate_synthetic_arpeggios.py.

Audio is decoded with soundfile instead of torchaudio.load().
This avoids the TorchCodec dependency introduced by newer
torchaudio versions.

The dataset computes a log-mel spectrogram aligned with the
saved frame-level note labels and returns fixed-length random
training crops.
"""

import csv
import os

import numpy as np
import soundfile as sf
import torch
import torchaudio
from torch.utils.data import Dataset


SAMPLE_RATE = 44100
HOP_LENGTH = 512
N_MELS = 128
N_FFT = 2048
CROP_FRAMES = 128


class ArpeggioDataset(Dataset):
    def __init__(
        self,
        data_dir: str,
        crop_frames: int = CROP_FRAMES,
    ):
        self.data_dir = data_dir
        self.crop_frames = crop_frames
        self.entries = []

        manifest_path = os.path.join(
            data_dir,
            "manifest.csv",
        )

        if not os.path.exists(manifest_path):
            raise FileNotFoundError(
                f"Manifest not found: {manifest_path}"
            )

        with open(
            manifest_path,
            newline="",
            encoding="utf-8",
        ) as f:
            for row in csv.DictReader(f):
                self.entries.append(row)

        if not self.entries:
            raise RuntimeError(
                f"No training examples found in {manifest_path}"
            )

        self.mel = torchaudio.transforms.MelSpectrogram(
            sample_rate=SAMPLE_RATE,
            n_fft=N_FFT,
            hop_length=HOP_LENGTH,
            n_mels=N_MELS,
        )

    def __len__(self) -> int:
        return len(self.entries)

    def __getitem__(self, index: int):
        entry = self.entries[index]

        audio_path = entry["audio_path"]
        label_path = entry["label_path"]

        if not os.path.exists(audio_path):
            raise FileNotFoundError(
                f"Audio file not found: {audio_path}"
            )

        if not os.path.exists(label_path):
            raise FileNotFoundError(
                f"Label file not found: {label_path}"
            )

        # ---------------------------------------------------------
        # Load audio using soundfile.
        #
        # Newer torchaudio versions use TorchCodec internally
        # for torchaudio.load(). soundfile avoids that dependency.
        # ---------------------------------------------------------
        audio, sr = sf.read(
            audio_path,
            always_2d=True,
            dtype="float32",
        )

        # soundfile returns:
        #     [samples, channels]
        #
        # PyTorch audio operations expect:
        #     [channels, samples]
        waveform = torch.from_numpy(
            audio.T.copy()
        )

        # ---------------------------------------------------------
        # Resample if the generated audio does not already use
        # the expected 44.1 kHz sample rate.
        # ---------------------------------------------------------
        if sr != SAMPLE_RATE:
            waveform = torchaudio.functional.resample(
                waveform,
                sr,
                SAMPLE_RATE,
            )

        # ---------------------------------------------------------
        # Convert stereo/multichannel audio to mono.
        # ---------------------------------------------------------
        if waveform.shape[0] > 1:
            waveform = waveform.mean(
                dim=0,
                keepdim=True,
            )

        # ---------------------------------------------------------
        # Generate log-mel spectrogram.
        #
        # Result:
        #     [N_MELS, time_frames]
        # ---------------------------------------------------------
        mel_spec = self.mel(
            waveform
        ).squeeze(0)

        mel_spec = torch.log(
            mel_spec.clamp(min=1e-6)
        )

        # ---------------------------------------------------------
        # Load frame-level note labels.
        #
        # Expected shape:
        #     [time_frames, NUM_NOTES]
        # ---------------------------------------------------------
        labels = torch.from_numpy(
            np.load(label_path)
        ).float()

        # ---------------------------------------------------------
        # Audio and labels can differ by one or two frames because
        # of STFT/frame rounding. Trim both to the shorter length.
        # ---------------------------------------------------------
        num_frames = min(
            mel_spec.shape[1],
            labels.shape[0],
        )

        if num_frames <= 0:
            raise RuntimeError(
                f"Empty audio/label sequence: "
                f"{audio_path}"
            )

        mel_spec = mel_spec[
            :,
            :num_frames,
        ]

        labels = labels[
            :num_frames,
            :,
        ]

        # ---------------------------------------------------------
        # Pad short examples.
        # ---------------------------------------------------------
        if num_frames < self.crop_frames:
            pad = self.crop_frames - num_frames

            mel_spec = torch.nn.functional.pad(
                mel_spec,
                (0, pad),
            )

            labels = torch.nn.functional.pad(
                labels,
                (0, 0, 0, pad),
            )

            start = 0

        # ---------------------------------------------------------
        # Random crop for normal-sized examples.
        # ---------------------------------------------------------
        else:
            max_start = (
                num_frames
                - self.crop_frames
                + 1
            )

            start = torch.randint(
                0,
                max_start,
                (1,),
            ).item()

        # ---------------------------------------------------------
        # Extract the same time region from both features and
        # labels.
        # ---------------------------------------------------------
        mel_crop = mel_spec[
            :,
            start:start + self.crop_frames,
        ]

        label_crop = labels[
            start:start + self.crop_frames,
            :,
        ]

        # Model input:
        #     [batch, 1, N_MELS, frames]
        #
        # Dataset output before batching:
        #     [1, N_MELS, frames]
        return (
            mel_crop.unsqueeze(0),
            label_crop,
        )
