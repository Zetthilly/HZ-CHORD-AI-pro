"""
Loads the synthetic arpeggio examples generated by generate_synthetic_arpeggios.py,
computes a log-mel spectrogram aligned frame-for-frame with the saved labels,
and yields fixed-length random crops for training.
"""

import csv
import os

import numpy as np
import torch
import torchaudio
from torch.utils.data import Dataset

SAMPLE_RATE = 44100
HOP_LENGTH = 512      # must match generate_synthetic_arpeggios.py
N_MELS = 128
N_FFT = 2048
CROP_FRAMES = 128     # ~1.5s per training crop at this hop length


class ArpeggioDataset(Dataset):
    def __init__(self, data_dir: str, crop_frames: int = CROP_FRAMES):
        self.data_dir = data_dir
        self.crop_frames = crop_frames
        self.entries = []
        with open(os.path.join(data_dir, "manifest.csv")) as f:
            for row in csv.DictReader(f):
                self.entries.append(row)

        self.mel = torchaudio.transforms.MelSpectrogram(
            sample_rate=SAMPLE_RATE,
            n_fft=N_FFT,
            hop_length=HOP_LENGTH,
            n_mels=N_MELS,
        )

    def __len__(self) -> int:
        return len(self.entries)

    def __getitem__(self, index: int):
        entry = self.entries[index]
        waveform, sr = torchaudio.load(entry["audio_path"])
        if sr != SAMPLE_RATE:
            waveform = torchaudio.functional.resample(waveform, sr, SAMPLE_RATE)
        if waveform.shape[0] > 1:
            waveform = waveform.mean(dim=0, keepdim=True)

        mel_spec = self.mel(waveform).squeeze(0)               # [N_MELS, T]
        mel_spec = torch.log(mel_spec.clamp(min=1e-6))          # log-mel, standard for this kind of model

        labels = torch.from_numpy(np.load(entry["label_path"])).float()  # [T_labels, NUM_NOTES]

        # Mel-spectrogram and label frame counts can differ by a frame or two due to
        # rounding — trim both to the shorter length so they line up exactly.
        num_frames = min(mel_spec.shape[1], labels.shape[0])
        mel_spec = mel_spec[:, :num_frames]
        labels = labels[:num_frames, :]

        if num_frames < self.crop_frames:
            pad = self.crop_frames - num_frames
            mel_spec = torch.nn.functional.pad(mel_spec, (0, pad))
            labels = torch.nn.functional.pad(labels, (0, 0, 0, pad))
            start = 0
        else:
            start = torch.randint(0, num_frames - self.crop_frames + 1, (1,)).item()

        mel_crop = mel_spec[:, start:start + self.crop_frames]           # [N_MELS, crop_frames]
        label_crop = labels[start:start + self.crop_frames, :]          # [crop_frames, NUM_NOTES]

        return mel_crop.unsqueeze(0), label_crop  # add channel dim: [1, N_MELS, crop_frames]
